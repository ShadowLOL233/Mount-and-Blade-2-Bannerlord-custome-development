# OSW Shield v2 override generator.
#
# Reads OSA_Reference/data/osa_items.csv (source_mod=OSW · Type=Shield · 114 rows),
# classifies each shield by (tier, weight class, material), computes new
# hit_points / body_armor / speed_rating per OSW_BALANCE_PROPOSAL.md v0.2,
# then clones the original OSW XML node and overrides the Weapon sub-element.
#
# Output: ModuleData/OSABalance_shield_override.xml (whole-node replacement,
# Bannerlord XML load convention).
#
# Load order in SubModule.xml: this xml must load AFTER OpenSourceWeaponry's
# own OSA_ar_reforms_shields.xml so ours wins. Since DependedModule declares
# OSW LoadBeforeThis, that ordering is automatic.

param(
    [string]$OsawWorkshopRoot = 'E:\SteamLibrary\steamapps\workshop\content\261550\3010984416\ModuleData',
    [string]$OswCsvPath       = (Join-Path $PSScriptRoot '..\..\OSA_Reference\data\osa_items.csv'),
    [string]$OutFile          = (Join-Path $PSScriptRoot '..\ModuleData\OSABalance_shield_override.xml')
)

$ErrorActionPreference = 'Stop'

Write-Host "== OSW Shield v2 override generator ==" -ForegroundColor Cyan

# ---------- classification rules (OSW_BALANCE_PROPOSAL.md v0.2) ----------
function Get-Tier([int]$hp) {
    if ($hp -le 260) { 'T1' }
    elseif ($hp -le 320) { 'T2' }
    elseif ($hp -le 380) { 'T3' }
    elseif ($hp -le 440) { 'T4' }
    elseif ($hp -le 500) { 'T5' }
    else { 'T6' }
}
function Get-WeightClass([double]$wt) {
    if ($wt -le 2.9) { 'Buckler' }
    elseif ($wt -le 4.2) { 'RoundLight' }
    elseif ($wt -le 5.5) { 'RoundStd' }
    else { 'HeavyScutum' }
}
function Get-Material([int]$ba) {
    if ($ba -le 2) { 'Wood' } else { 'Reinforced' }
}

$tierHp = @{ T1=380; T2=480; T3=570; T4=700; T5=750; T6=800 }
$wtMult = @{ Buckler=0.85; RoundLight=0.95; RoundStd=1.00; HeavyScutum=1.10 }
$wtSpd  = @{ Buckler=+2;   RoundLight=+1;   RoundStd=0;    HeavyScutum=-1 }
$wtBa   = @{ Buckler=0;    RoundLight=0;    RoundStd=0;    HeavyScutum=+1 }
$baWood       = @{ T1=1; T2=2; T3=3; T4=3; T5=4; T6=4 }
$baReinforced = @{ T1=3; T2=4; T3=5; T4=6; T5=7; T6=8 }
$baseSpd = 84

function Compute-NewStats([int]$curHp, [int]$curBa, [double]$wt) {
    $tier = Get-Tier $curHp
    $wc   = Get-WeightClass $wt
    $mat  = Get-Material $curBa

    $baseHp = $tierHp[$tier]
    $newHp  = [math]::Round($baseHp * $wtMult[$wc])

    $baseBa = if ($mat -eq 'Wood') { $baWood[$tier] } else { $baReinforced[$tier] }
    $newBa  = $baseBa + $wtBa[$wc]
    # Buckler caps ba at 2 regardless of material
    if ($wc -eq 'Buckler' -and $newBa -gt 2) { $newBa = 2 }
    if ($newBa -lt 0) { $newBa = 0 }

    $newSpd = $baseSpd + $wtSpd[$wc]

    return @{
        tier=$tier; weightClass=$wc; material=$mat
        hp=$newHp; ba=$newBa; spd=$newSpd
    }
}

# ---------- load OSW shields ----------
if (-not (Test-Path -LiteralPath $OswCsvPath)) {
    throw "Missing OSW CSV: $OswCsvPath (rerun OSA_Reference/scripts/extract_osa.ps1)"
}
$oswShields = Import-Csv -LiteralPath $OswCsvPath | Where-Object {
    $_.source_mod -eq 'OSW' -and $_.Type -eq 'Shield'
}
Write-Host "Loaded $($oswShields.Count) OSW shields from CSV" -ForegroundColor Green

# Build decisions
$decisions = [ordered]@{}
foreach ($r in $oswShields) {
    $stats = Compute-NewStats -curHp ([int]$r.'Weapon.hit_points') -curBa ([int]$r.'Weapon.body_armor') -wt ([double]$r.weight)
    $decisions[$r.id] = $stats
}
Write-Host "Computed $($decisions.Count) shield decisions" -ForegroundColor Green

# Group summary
$decisions.Values | Group-Object { "$($_.tier) · $($_.weightClass) · $($_.material) → hp=$($_.hp) ba=$($_.ba) spd=$($_.spd)" } | Sort-Object Name | ForEach-Object {
    Write-Host ("  {0,3}x {1}" -f $_.Count, $_.Name)
}

# ---------- index OSW workshop XMLs ----------
if (-not (Test-Path -LiteralPath $OsawWorkshopRoot)) {
    throw "OSW workshop dir not found: $OsawWorkshopRoot"
}
$idToNode = @{}
$xmlFiles = Get-ChildItem -LiteralPath $OsawWorkshopRoot -Filter '*.xml' -File
Write-Host "Found $($xmlFiles.Count) OSW xml files to scan" -ForegroundColor DarkGray
foreach ($xf in $xmlFiles) {
    try {
        [xml]$doc = Get-Content -LiteralPath $xf.FullName -Encoding UTF8
        $items = $doc.SelectNodes('//Item')
        foreach ($item in $items) {
            $iid = $item.GetAttribute('id')
            if ($iid -and -not $idToNode.ContainsKey($iid)) {
                $idToNode[$iid] = @{ Node = $item; Source = $xf.FullName }
            }
        }
    } catch {
        Write-Warning "Parse fail: $($xf.FullName) - $_"
    }
}
Write-Host "Indexed $($idToNode.Count) OSW items across workshop xml" -ForegroundColor Green

# ---------- build output XML ----------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine('<!-- OSABalance shield override - generated by src/manual_override_shield.ps1. -->')
[void]$sb.AppendLine('<!-- OSW 114 shields rebalanced per OSW_BALANCE_PROPOSAL.md v0.2 (2026-09-25). -->')
[void]$sb.AppendLine('<!-- Bannerlord same-id load convention: this replaces OSW OSA_ar_reforms_shields.xml + OSA_extra_contribution_weapons.xml entries. -->')
[void]$sb.AppendLine('<Items>')

$found = 0
$missing = @()

foreach ($id in $decisions.Keys) {
    if (-not $idToNode.ContainsKey($id)) {
        $missing += $id
        continue
    }
    $entry = $idToNode[$id]
    $orig = $entry.Node
    $d = $decisions[$id]

    # Clone original node so we can mutate safely
    $doc = New-Object System.Xml.XmlDocument
    $imported = $doc.ImportNode($orig, $true)

    # Locate Weapon sub-element (path: Item/ItemComponent/Weapon) via XPath
    $weaponNode = $imported.SelectSingleNode('ItemComponent/Weapon')
    if (-not $weaponNode) {
        $missing += "$id (no Weapon node)"
        continue
    }

    # Apply new stats
    $weaponNode.SetAttribute('hit_points',   "$($d.hp)")
    $weaponNode.SetAttribute('body_armor',   "$($d.ba)")
    $weaponNode.SetAttribute('speed_rating', "$($d.spd)")

    # Serialize with 2-space indent
    $settings = New-Object System.Xml.XmlWriterSettings
    $settings.Indent = $true
    $settings.IndentChars = '  '
    $settings.OmitXmlDeclaration = $true

    $sw = New-Object System.IO.StringWriter
    $xw = [System.Xml.XmlWriter]::Create($sw, $settings)
    $imported.WriteTo($xw)
    $xw.Flush()
    [void]$sb.AppendLine("  " + $sw.ToString())
    $found++
}

[void]$sb.AppendLine('</Items>')

# Resolve output path
$outResolved = $null
try { $outResolved = Resolve-Path -LiteralPath $OutFile -ErrorAction Stop } catch {
    $outDir = Split-Path $OutFile -Parent
    if (-not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }
    $outResolved = $OutFile
}

Set-Content -LiteralPath $outResolved -Value $sb.ToString() -Encoding UTF8
Write-Host ""
Write-Host "Wrote $found items to $outResolved" -ForegroundColor Green
if ($missing.Count -gt 0) {
    Write-Warning "Missing items ($($missing.Count)):"
    $missing | ForEach-Object { Write-Warning "  $_" }
}
